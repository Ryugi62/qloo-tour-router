// Builds src/domain/data/usMarkets.ts from two PUBLIC Census Bureau sources (no scraping, no personal data):
//  population: https://www2.census.gov/programs-surveys/popest/datasets/2020-2024/metro/totals/cbsa-est2024-alldata.csv  (POPESTIMATE2024, Metropolitan Statistical Areas)
//  coordinates: https://tigerweb.geo.census.gov/arcgis/rest/services/TIGERweb/CBSA/MapServer/3  (INTPTLAT/INTPTLON, MSA internal point)
// Run: node scripts/build-markets.mjs   (output is committed; the app never calls these URLs)
import { writeFileSync } from 'node:fs';
const POP_URL = 'https://www2.census.gov/programs-surveys/popest/datasets/2020-2024/metro/totals/cbsa-est2024-alldata.csv';
const GEO_URL = 'https://tigerweb.geo.census.gov/arcgis/rest/services/TIGERweb/CBSA/MapServer/3/query?where=1%3D1&outFields=GEOID,INTPTLAT,INTPTLON&returnGeometry=false&resultRecordCount=2000&f=json';
const MIN_POP = 100_000;
const csv = new TextDecoder('latin1').decode(await (await fetch(POP_URL)).arrayBuffer());
const geo = (await (await fetch(GEO_URL)).json()).features.map((f) => f.attributes);
const coord = new Map(geo.map((g) => [String(g.GEOID), { lat: Number(g.INTPTLAT), lon: Number(g.INTPTLON) }]));
const rows = csv.trim().split(/\r?\n/);
const head = rows[0].split(',');
const parse = (line) => { const out = []; let cur = '', q = false; for (const ch of line) { if (ch === '"') q = !q; else if (ch === ',' && !q) { out.push(cur); cur = ''; } else cur += ch; } out.push(cur); return out; };
const idx = (n) => head.indexOf(n);
const out = [];
for (const line of rows.slice(1)) {
  const c = parse(line);
  if (c[idx('LSAD')] !== 'Metropolitan Statistical Area') continue;
  const pop = Number(c[idx('POPESTIMATE2024')]);
  const xy = coord.get(c[idx('CBSA')]);
  if (!(pop >= MIN_POP) || !xy) continue;
  const [citiesPart, statesPart] = c[idx('NAME')].split(', ');
  const cities = citiesPart.includes('--') ? citiesPart.split('--') : citiesPart.split('-');
  out.push({ id: c[idx('CBSA')], name: c[idx('NAME')], cities: [...new Set([citiesPart.split('--')[0], ...cities])], states: statesPart.split('-'), pop, lat: +xy.lat.toFixed(3), lon: +xy.lon.toFixed(3) });
}
out.sort((a, b) => b.pop - a.pop);
const body = `// GENERATED by scripts/build-markets.mjs — do not edit by hand.
// Population: US Census Bureau, Vintage 2024 metropolitan statistical area estimates (POPESTIMATE2024)
//   ${POP_URL}
// Coordinates: Census TIGERweb CBSA layer, MSA internal point (INTPTLAT/INTPTLON)
//   https://tigerweb.geo.census.gov/arcgis/rest/services/TIGERweb/CBSA/MapServer/3
// Public statistics, fetched once at build time (no scraping at runtime, no personal data). ${out.length} metros with >= ${MIN_POP} people.
export interface MarketRow { readonly id: string; readonly name: string; readonly cities: readonly string[]; readonly states: readonly string[]; readonly pop: number; readonly lat: number; readonly lon: number }
export const US_MARKETS: readonly MarketRow[] = ${JSON.stringify(out)};
`;
writeFileSync(new URL('../src/domain/data/usMarkets.ts', import.meta.url), body);
